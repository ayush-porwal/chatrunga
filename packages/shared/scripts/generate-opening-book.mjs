#!/usr/bin/env node
/**
 * Builds the bundled opening book (src/chess/opening-book-data.ts) from lichess-org/chess-openings
 * (CC0 1.0, https://github.com/lichess-org/chess-openings): every named opening of a.tsv–e.tsv
 * (ECO code, name, PGN).
 *
 *   pnpm --filter @chaturanga/shared generate:opening-book            # the pinned commit below
 *   pnpm --filter @chaturanga/shared generate:opening-book -- <dir>   # local copies of the TSVs
 *
 * The lines are replayed with chessops and stored as one move tree (lines share their first
 * moves), so the asset stays small: one row per move, depth-first,
 *
 *   <depth> <uci> [<eco> <name>]       (tab-separated; depth 1 is the first move)
 *
 * with the ECO code and name on the move that reaches a named position. Reading it back (see
 * parseOpeningBook in opening-book.ts) replays the tree and keys every position by its EPD, so a
 * move order the data doesn't list still finds the position (a transposition). The script checks
 * that every line replays, and that no position carries two names, before writing anything.
 *
 * After changing the data, bump MOVE_ASSESSMENT_POLICY (chess/move-assessment.ts): saved reviews
 * then re-assess their book moves when they open.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { constants, zstdCompressSync } from "node:zlib";
import { Chess } from "chessops/chess";
import { makeFen } from "chessops/fen";
import { parseSan } from "chessops/san";
import { makeUci } from "chessops/util";

const REPOSITORY = "lichess-org/chess-openings";
/** The commit the bundled data comes from (2026-10-03). */
const COMMIT = "5a13018164f6bd88f48b3dc31a8e2a39f31a060a";
const FILES = ["a.tsv", "b.tsv", "c.tsv", "d.tsv", "e.tsv"];

const here = dirname(fileURLToPath(import.meta.url));
const output = join(here, "..", "src", "chess", "opening-book-data.ts");

function openingBookModule(openings) {
  return `// Generated by packages/shared/scripts/generate-opening-book.mjs; do not edit.
//
// The ${openings} named openings of lichess-org/chess-openings
// (https://github.com/${REPOSITORY}), commit ${COMMIT},
// files ${FILES.join(", ")}. That data is dedicated to the public domain under CC0 1.0
// (https://creativecommons.org/publicdomain/zero/1.0/).
//
// Zstd of the move tree, one row per move, depth-first: "<depth>\t<uci>[\t<eco>\t<name>]".
// openingBookText() inflates the sibling .txt.zst for parseOpeningBook.

import { readFileSync } from "node:fs";
import { zstdDecompressSync } from "node:zlib";
import { fileURLToPath } from "node:url";

const compressed = readFileSync(fileURLToPath(new URL("./opening-book.txt.zst", import.meta.url)));

let text: string | null = null;

/** The book's move tree, inflated once. */
export function openingBookText(): string {
  text ??= zstdDecompressSync(compressed).toString("utf8");
  return text;
}
`;
}

async function readTsv(file, localDir) {
  if (localDir) return readFileSync(join(localDir, file), "utf8");
  const url = `https://raw.githubusercontent.com/${REPOSITORY}/${COMMIT}/${file}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

/** A tree node: its children by UCI, and the name of the position it reaches (if any). */
function node() {
  return { children: new Map(), name: null };
}

const root = node();
/** Named positions by EPD, to refuse two names for one position. */
const namedAt = new Map();
let openings = 0;

const localDir = process.argv[2];
for (const file of FILES) {
  const rows = (await readTsv(file, localDir)).trim().split("\n");
  if (rows[0] !== "eco\tname\tpgn") throw new Error(`${file}: unexpected header ${rows[0]}`);
  for (const row of rows.slice(1)) {
    const [eco, name, pgn, ...rest] = row.split("\t");
    if (!eco || !name || !pgn || rest.length) throw new Error(`${file}: bad row ${row}`);
    if (!/^[A-E]\d\d$/.test(eco) || /[\t`$\\]/.test(name)) throw new Error(`${file}: bad ${row}`);
    const pos = Chess.default();
    let at = root;
    for (const token of pgn.split(" ")) {
      if (/^\d+\.$/.test(token)) continue;
      const move = parseSan(pos, token);
      if (!move) throw new Error(`${file}: illegal ${token} in ${pgn}`);
      const uci = makeUci(move);
      pos.play(move);
      if (!at.children.has(uci)) at.children.set(uci, node());
      at = at.children.get(uci);
    }
    const epd = makeFen(pos.toSetup(), { epd: true });
    if (namedAt.has(epd)) throw new Error(`${name}: same position as ${namedAt.get(epd)}`);
    namedAt.set(epd, name);
    at.name = `${eco}\t${name}`;
    openings += 1;
  }
}

const lines = [];
function write(at, depth) {
  // Sorted, so the file only changes when the data does.
  for (const uci of [...at.children.keys()].sort((a, b) => a.localeCompare(b, "en"))) {
    const child = at.children.get(uci);
    lines.push(child.name ? `${depth}\t${uci}\t${child.name}` : `${depth}\t${uci}`);
    write(child, depth + 1);
  }
}
write(root, 1);

const text = `${lines.join("\n")}\n`;
writeFileSync(
  output.replace(/\.ts$/, ".txt.zst"),
  zstdCompressSync(Buffer.from(text), {
    params: { [constants.ZSTD_c_compressionLevel]: 19 }
  })
);
writeFileSync(output, openingBookModule(openings));
console.log(`${openings} openings, ${lines.length} moves -> ${output}`);
